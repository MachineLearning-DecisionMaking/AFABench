def _load_figure_module() -> ModuleType:
    path = ROOT / "scripts/plotting/plot_main_summary.py"
    spec = importlib.util.spec_from_file_location("plot_main_summary", path)
    if spec is None or spec.loader is None:
        message = f"cannot load {path}"
        raise ImportError(message)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _metric(dataset: str) -> str:
    return "accuracy" if dataset in SYNTHETIC else "f_score"


def _largest_budget(frame: pd.DataFrame) -> pd.DataFrame:
    largest = frame.groupby("dataset")["eval_hard_budget"].transform("max")
    return cast("pd.DataFrame", frame[frame["eval_hard_budget"] == largest])


def _scores(paths: list[Path]) -> pd.DataFrame:
    frames = []
    for path in paths:
        frame = _largest_budget(pd.read_csv(path))
        frame = frame.assign(
            score=[
                row[f"{_metric(str(row['dataset']))}_mean"]
                for _, row in frame.iterrows()
            ]
        )
        frames.append(
            frame[["dataset", "method", "mechanism", "p", "strategy", "score"]]
        )
    merged = pd.concat(frames).astype({"p": float})
    return merged.drop_duplicates(
        ["dataset", "method", "mechanism", "p", "strategy"], keep="first"
    )


def _instances(path: Path) -> pd.DataFrame:
    frame = _largest_budget(pd.read_csv(path))
    frame = frame.assign(
        score=[
            row[_metric(str(row["dataset"]))] for _, row in frame.iterrows()
        ]
    )
    return frame.astype({"p": float})


def _cell(
    scores: pd.DataFrame, dataset: str, method: str, mechanism: str, p: float
) -> dict[str, float]:
    selected = scores[
        (scores["dataset"] == dataset)
        & (scores["method"] == method)
        & (scores["mechanism"] == mechanism)
        & (scores["p"] == p)
    ]
    return dict(
        zip(selected["strategy"], selected["score"].astype(float), strict=True)
    )


def _complete(scores: pd.DataFrame, dataset: str, method: str) -> float:
    selected = scores[
        (scores["dataset"] == dataset)
        & (scores["method"] == method)
        & (scores["strategy"] == "complete")
    ]
    return float(selected["score"].mean()) if len(selected) else math.nan


def _fmt(value: float, digits: int = 2) -> str:
    return f"${value:.{digits}f}$" if np.isfinite(value) else "--"


def _write(name: str, body: str) -> None:
    path = RESULTS / name
    path.write_text(HEADER + body)
    print(f"wrote {path}")


def recovery_table(figure: ModuleType) -> None:
    panel = figure.collect_panel_b(SUMMARY_ROOT)
    rng = np.random.default_rng(figure.SEED)
    rows = []
    for method, label in METHODS.items():
        cells = []
        for mechanism in MECHANISMS:
            subset = panel[panel["mechanism"] == mechanism]
            share, low, high = figure._share(subset, method, rng)  # noqa: SLF001
            cells.append(
                f"{_fmt(share)} \\scriptsize{{[{low:.2f}, {high:.2f}]}}"
            )
        rows.append(f"{label} & " + " & ".join(cells) + r" \\")
    _write(
        "recovery_shares.tex",
        r"""\begin{table}[H]
\centering
\caption{Fraction of the missingness damage recovered by generative restoration, estimated as the least-squares slope through the origin of the restoration gain against the missingness damage over the eight datasets and the three missingness rates, as in \Cref{fig:law-grid}, with 95\% bootstrap intervals.}
\label{tab:recovery-shares}
{\footnotesize
\begin{tabular}{l"""
        + "c" * len(MECHANISMS)
        + r"""}
\toprule
Method & """
        + " & ".join(MECHANISMS.values())
        + r""" \\
\midrule
"""
        + "\n".join(rows)
        + r"""
\bottomrule
\end{tabular}
}
\end{table}
""",
    )


def significance_table(instances: pd.DataFrame) -> None:
    rows = []
    for mechanism, label in MECHANISMS.items():
        for p in sorted(
            instances.loc[instances["mechanism"] == mechanism, "p"].unique()
        ):
            counts = {"all": [0, 0, 0], "damaged": [0, 0, 0]}
            recovered = []
            selected = instances[
                (instances["mechanism"] == mechanism) & (instances["p"] == p)
            ]
            for key, cell in selected.groupby(["dataset", "method"]):
                dataset, method = cast("tuple[str, str]", key)
                complete = instances[
                    (instances["dataset"] == dataset)
                    & (instances["method"] == method)
                    & (instances["strategy"] == "complete")
                ]["score"].mean()
                pivot = cell.pivot_table(
                    index="instance", columns="strategy", values="score"
                )
                if not {"restricted", "pvae_label_conditioned"} <= set(
                    pivot.columns
                ):
                    continue
                difference = (
                    pivot["pvae_label_conditioned"] - pivot["restricted"]
                ).dropna()
                damage = complete - pivot["restricted"].mean()
                pvalue = float(
                    cast("Any", stats.ttest_1samp(difference, 0.0)).pvalue
                )
                index = (
                    0
                    if pvalue < ALPHA and difference.mean() > 0
                    else 1
                    if pvalue < ALPHA
                    else 2
                )
                counts["all"][index] += 1
                if damage >= DAMAGE_THRESHOLD:
                    counts["damaged"][index] += 1
                    recovered.append(difference.mean() / damage)
            rows.append(
                f"{label} & ${p:g}$ & "
                + " & ".join(f"${value}$" for value in counts["all"])
                + f" & ${sum(counts['damaged'])}$ & "
                + " & ".join(f"${value}$" for value in counts["damaged"])
                + f" & {_fmt(float(np.median(recovered)))} \\\\"
            )
    _write(
        "restoration_significance.tex",
        r"""\begin{table}[H]
\centering
\caption{Generative restoration against restricted training, per method--dataset pair, with a paired $t$-test over the five dataset splits at $\alpha = 0.05$ (uncorrected). Damaged pairs have a missingness damage of at least $0.01$; the last column is the median fraction of the damage recovered over the damaged pairs.}
\label{tab:restoration-significance}
{\footnotesize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lcccccccccc}
\toprule
& & \multicolumn{3}{c}{All Pairs} & \multicolumn{5}{c}{Damaged Pairs} \\
\cmidrule(lr){3-5} \cmidrule(lr){6-10}
Mechanism & $p$ & Better & Worse & n.s. & Pairs & Better & Worse & n.s. & Recovered \\
\midrule
"""
        + "\n".join(rows)
        + r"""
\bottomrule
\end{tabular}
}
\end{table}
""",
    )


def complete_instances_table(namespaces: list[str]) -> None:
    sizes: dict[str, tuple[int, int]] = {}
    for namespace in namespaces:
        root = DATASET_ROOT / namespace
        if not root.exists():
            continue
        for directory in sorted(root.iterdir()):
            bundle = directory / "0" / "train.bundle"
            if directory.name in sizes or not bundle.exists():
                continue
            dataset, _ = load_bundle(bundle)
            features, _ = cast("Any", dataset).get_all_data()
            sizes[directory.name] = (len(features), features[0].numel())
    rows = []
    for dataset, (n, d) in sorted(sizes.items(), key=lambda item: item[1][1]):
        expected = [n * (1 - p) ** d for p in (0.3, 0.5, 0.7)]
        rows.append(
            f"{DATASET_LABELS_SHORT.get(dataset, dataset)} & ${n}$ & ${d}$ & "
            + " & ".join(f"$\\num{{{value:.1e}}}$" for value in expected)
            + r" \\"
        )
    _write(
        "complete_instances.tex",
        r"""\begin{table}[H]
\centering
\caption{Expected number of complete training instances $n (1 - p)^d$ under MCAR, per dataset split.}
\label{tab:complete-instances}
{\footnotesize
\begin{tabular}{lccccc}
\toprule
Dataset & $n$ & $d$ & $p = 0.3$ & $p = 0.5$ & $p = 0.7$ \\
\midrule
"""
        + "\n".join(rows)
        + r"""
\bottomrule
\end{tabular}
}
\end{table}
""",
    )


def mask_conditioning_table(scores: pd.DataFrame) -> None:
    rows = []
    datasets = sorted(scores["dataset"].unique())
    for label, (aliasing, filtering) in VARIANT_PAIRS.items():
        wins = {"restricted": 0, "pvae_label_conditioned": 0}
        total = 0
        for mechanism in MECHANISMS:
            for p in (0.3, 0.5, 0.7):
                for dataset in datasets:
                    alias = _cell(scores, dataset, aliasing, mechanism, p)
                    filt = _cell(scores, dataset, filtering, mechanism, p)
                    if not alias or not filt:
                        continue
                    total += 1
                    for strategy in wins:
                        if alias.get(strategy, -1) > filt.get(
                            strategy, math.inf
                        ):
                            wins[strategy] += 1
        rows.append(
            f"{label} & ${wins['restricted']}$ / ${total}$ & "
            f"${wins['pvae_label_conditioned']}$ / ${total}$ \\\\"
        )
    _write(
        "mask_conditioning.tex",
        r"""\begin{table}[H]
\centering
\caption{Number of settings (mechanism, rate and dataset) in which the aliasing variant $(s)$ outperforms the filtering variant $(s,m)$.}
\label{tab:mask-conditioning}
{\footnotesize
\begin{tabular}{lcc}
\toprule
Method & Restricted Training & Generative Restoration \\
\midrule
"""
        + "\n".join(rows)
        + r"""
\bottomrule
\end{tabular}
}
\end{table}
""",
    )


def approaches_table(scores: pd.DataFrame) -> None:
    datasets = set(scores["dataset"].unique())
    groups = {
        "Synthetic": SYNTHETIC & datasets,
        "Real-World": frozenset(datasets - SYNTHETIC),
    }
    present = [
        strategy
        for strategy in APPROACHES
        if strategy != "true_completion"
        and (scores["strategy"] == strategy).any()
    ]
    shares: dict[str, list[str]] = {strategy: [] for strategy in APPROACHES}
    for members in groups.values():
        cells = []
        for dataset in sorted(members):
            for method in METHODS:
                cell = _cell(scores, dataset, method, "mcar", float(RATE))
                complete = _complete(scores, dataset, method)
                if "restricted" not in cell or not set(present) <= set(cell):
                    continue
                if complete - cell["restricted"] >= DAMAGE_THRESHOLD:
                    cells.append((cell, complete))
        damage = sum(complete - cell["restricted"] for cell, complete in cells)
        for strategy in APPROACHES:
            if strategy == "true_completion" and cells:
                value = 1.0
            elif strategy in present and cells:
                gain = sum(
                    cell[strategy] - cell["restricted"] for cell, _ in cells
                )
                value = gain / damage
            else:
                value = math.nan
            shares[strategy].append(f"{_fmt(value)} & ${len(cells)}$")
    rows = [
        f"{label} & " + " & ".join(shares[strategy]) + r" \\"
        for strategy, label in APPROACHES.items()
    ]
    _write(
        "restoration_approaches.tex",
        r"""\begin{table}[H]
\centering
\caption{Fraction of the missingness damage recovered by each restoration approach under MCAR at $p = 0.7$, summed over the method--dataset pairs with a damage of at least $0.01$ for which every listed approach is available. True completion trains on the complete training data and recovers the full damage by construction.}
\label{tab:restoration-approaches}
{\footnotesize
\begin{tabular}{lcccc}
\toprule
& \multicolumn{2}{c}{Synthetic} & \multicolumn{2}{c}{Real-World} \\
\cmidrule(lr){2-3} \cmidrule(lr){4-5}
Restoration Approach & Recovered ($\uparrow$) & Pairs & Recovered ($\uparrow$) & Pairs \\
\midrule
"""
        + "\n".join(rows)
        + r"""
\bottomrule
\end{tabular}
}
\end{table}
""",
    )


def predictor_table(paper: pd.DataFrame, view: pd.DataFrame) -> None:
    datasets = set(view["dataset"].unique())
    groups = {
        "Synthetic": SYNTHETIC & datasets,
        "Real-World": frozenset(datasets - SYNTHETIC),
    }
    rows = []
    for setting, source in (
        ("Complete-Data Predictor", paper),
        ("Predictor Trained on Training Data", view),
    ):
        entries = []
        for members in groups.values():
            pairs = []
            for dataset in sorted(members):
                for method in METHODS:
                    cell = _cell(source, dataset, method, "mcar", float(RATE))
                    available = _cell(
                        view, dataset, method, "mcar", float(RATE)
                    )
                    complete = _complete(paper, dataset, method)
                    if "restricted" in cell and "restricted" in available:
                        pairs.append((cell, complete))
            damages = [
                complete - cell["restricted"] for cell, complete in pairs
            ]
            damaged = [
                (cell, complete)
                for cell, complete in pairs
                if complete - cell["restricted"] >= DAMAGE_THRESHOLD
            ]
            total = sum(
                complete - cell["restricted"] for cell, complete in damaged
            )
            shares = []
            for strategy in ("pvae_label_conditioned", "mean_fill"):
                usable = [(c, k) for c, k in damaged if strategy in c]
                gain = sum(c[strategy] - c["restricted"] for c, _ in usable)
                shares.append(
                    gain / total
                    if usable and total and len(usable) == len(damaged)
                    else math.nan
                )
            entries.append(
                f"{_fmt(float(np.mean(damages)), 3) if damages else '--'} & "
                + " & ".join(_fmt(value) for value in shares)
            )
        rows.append(f"{setting} & " + " & ".join(entries) + r" \\")
    _write(
        "predictor_ablation.tex",
        r"""\begin{table}[H]
\centering
\caption{Mean missingness damage and fraction of the damage recovered under MCAR at $p = 0.7$, with the predictor trained on complete data, as in the main experiments, or on the same incomplete or restored training data as the policy. Damage is measured against complete-data training with the complete-data predictor; the recovered fractions are summed over the method--dataset pairs with a damage of at least $0.01$.}
\label{tab:predictor-ablation}
{\footnotesize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lcccccc}
\toprule
& \multicolumn{3}{c}{Synthetic} & \multicolumn{3}{c}{Real-World} \\
\cmidrule(lr){2-4} \cmidrule(lr){5-7}
Predictor & Damage & PVAE ($\uparrow$) & Mean-Fill ($\uparrow$) & Damage & PVAE ($\uparrow$) & Mean-Fill ($\uparrow$) \\
\midrule
"""
        + "\n".join(rows)
        + r"""
\bottomrule
\end{tabular}
}
\end{table}
""",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--namespace", default="induced")
    parser.add_argument(
        "--extra-namespaces",
        nargs="*",
        default=[
            "core_group_missingness_v2",
            "induced_real_missingness_v2",
            "induced_nonuniform_missingness_v2",
            "core_group_missingness_v2_e2b",
            "induced_real_missingness_v2_e2b",
            "induced_nonuniform_missingness_v2_e2b",
            "sklearn_imputers_core_group",
            "sklearn_imputers_induced_real",
            "sklearn_imputers_induced_nonuniform",
            "multi_draw_core_group",
            "multi_draw_induced_real",
            "multi_draw_induced_nonuniform",
        ],
    )
    arguments = parser.parse_args()
    paths = [SUMMARY_ROOT / arguments.namespace / "summary.csv"] + [
        SUMMARY_ROOT / name / "summary.csv"
        for name in arguments.extra_namespaces
        if (SUMMARY_ROOT / name / "summary.csv").exists()
    ]
    scores = _scores(paths)
    paper = _scores(paths[:1])
    instances = _instances(
        SUMMARY_ROOT / arguments.namespace / "instance_metrics.csv"
    )
    figure = _load_figure_module()

    recovery_table(figure)
    significance_table(instances)
    complete_instances_table(arguments.extra_namespaces[:3])
    mask_conditioning_table(paper)
    approaches_table(scores)
    view_paths = [
        SUMMARY_ROOT / f"view_classifier_{group}" / "summary.csv"
        for group in ("core_group", "induced_real", "induced_nonuniform")
    ]
    view_paths = [path for path in view_paths if path.exists()]
    if view_paths:
        predictor_table(scores, _scores(view_paths))


if __name__ == "__main__":
    main()
