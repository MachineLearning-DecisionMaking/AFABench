r"""
Relate missingness damage to how far each method beats a static route.

Reads the family summary of `plot_main_summary.py` and the route descriptors
of `route_redundancy.py`, and writes `tab:adaptivity`: per method, the mean
complete-data score, its margin over $V_{\mathrm{static}}$, and the damage.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import cast

import pandas as pd

from scripts.analysis.route_structure_table import collect
from scripts.plotting.family_summary import FAMILY_LABELS


def adaptivity(
    cells: pd.DataFrame, routes: pd.DataFrame, *, mechanism: str, p: float
) -> pd.DataFrame:
    selected = cells.loc[(cells["mechanism"] == mechanism) & (cells["p"] == p)]
    static = routes.set_index("dataset")["v_static"]
    missing = sorted(set(selected["dataset"]) - set(static.index))
    if missing:
        msg = f"no static route for datasets {missing}"
        raise ValueError(msg)
    frame = selected.assign(
        margin=selected["ceiling_abs"]
        - selected["dataset"].map(static).astype(float)
    )
    return frame[["dataset", "method", "ceiling_abs", "margin", "damage"]]


def render(frame: pd.DataFrame, *, mechanism: str, p: float) -> str:
    means = cast(
        "pd.DataFrame",
        frame.groupby("method")[["ceiling_abs", "margin", "damage"]].mean(),
    ).sort_values(by="damage")
    margin = cast("pd.Series", frame["margin"])
    damage = cast("pd.Series", frame["damage"])
    pearson = margin.corr(damage)
    spearman = margin.corr(damage, method="spearman")
    lines = [
        "% Generated by scripts/analysis/adaptivity_table.py.",
        "% Regenerate rather than editing by hand.",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{Complete-data score, its margin over the static route "
        "$V_{\\mathrm{static}}$ (\\Cref{tab:route-structure}), and "
        f"missingness damage under {mechanism.upper()} at $p={p:g}$, "
        "averaged over the eight datasets and, for \\JAFA{}, \\OL{} and "
        "\\ODIN{}, over both state representations.",
        f"Across method--dataset combinations, Pearson $r={pearson:.2f}$ and "
        f"Spearman $\\rho={spearman:.2f}$ between margin and damage.}}",
        "\\label{tab:adaptivity}",
        "{\\footnotesize",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Method & Complete & Margin over $V_{\\mathrm{static}}$ & Damage \\\\",
        "\\midrule",
    ]
    for method, row in means.iterrows():
        label = f"\\{FAMILY_LABELS[str(method)]}{{}}"
        lines.append(
            f"{label} & ${row['ceiling_abs']:.3f}$ & "
            f"${row['margin']:+.3f}$ & ${row['damage']:+.3f}$ \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "}", "\\end{table}"]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--cells",
        type=Path,
        default=Path(
            "extra/output/missing_data/analysis_figures/"
            "main_summary.family_cells.csv"
        ),
    )
    parser.add_argument(
        "--routes",
        type=Path,
        default=Path(
            "extra/output/missing_data/analysis/route_redundancy_induced_val.csv"
        ),
    )
    parser.add_argument("--mechanism", default="mcar")
    parser.add_argument("--p", type=float, default=0.7)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("extra/output/paper/experiments/results/adaptivity.tex"),
    )
    args = parser.parse_args()
    frame = adaptivity(
        pd.read_csv(args.cells),
        collect([args.routes]),
        mechanism=args.mechanism,
        p=args.p,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        render(frame, mechanism=args.mechanism, p=args.p) + "\n"
    )
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
