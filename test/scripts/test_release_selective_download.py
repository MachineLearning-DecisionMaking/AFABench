def write_release_outputs(
    root: Path,
    release_id: str,
    *,
    smoke_test: bool = False,
    omit: Iterable[str] = (),
    job_records: bool = False,
) -> None:
    """
    Write every artifact of the catalog, except those in `omit`.

    Each transformed table, bundle and the plot holds the release id, so a
    test can tell which release a restored file came from. `job_records`
    adds a completed and a failed job record.
    """
    write_catalog(
        root,
        replace(CATALOG, smoke_test=smoke_test),
        content=release_id,
        omit=omit,
    )
    (root / PLOT).parent.mkdir(parents=True)
    (root / PLOT).write_text(release_id)
    if job_records:
        write_job_record(root, JOB_RECORD, smoke_test=smoke_test)
        write_job_record(
            root,
            FAILED_JOB_RECORD,
            exit_status="failed",
            smoke_test=smoke_test,
        )


JOB_RECORD = (
    f"trained_methods/{TAG}/alpha/dataset-cube+realization_index-0/"
    "NO_PRETRAIN/train_seed-0+train_hard_budget-3+train_soft_budget_param-null/"
    "method.job_record.json"
)
FAILED_JOB_RECORD = "failed_job_records/" + JOB_RECORD.replace(
    "method.job_record.json",
    "method.20261001T000000000000Z-1a2b3c4d.job_record.json",
)
RELEASE_MANIFEST = "release_manifest.json"
TABLE = "release_job_duration_table.parquet"


def invoke(transport: FakeReleaseTransport, *args: str) -> Result:
    return runner.invoke(
        app,
        [*args, "--repo-id", REPO_ID],
        obj=lambda _repo_id: transport,
    )


def publish(
    tmp_path: Path,
    transport: FakeReleaseTransport,
    release_id: str,
    *,
    created_at: str = "2026-10-01T00:00:00+00:00",
    smoke_test: bool = False,
    omit: Iterable[str] = (),
    backdate: bool = False,
    job_records: bool = False,
    local_only: bool = False,
) -> Path:
    """
    Save and publish a release whose manifest has `created_at`.

    `backdate` gives every saved output a distinct old mtime first. Smoke
    and `local_only` packages, which publication refuses, are laid out on
    the local host directly to exercise permissive download reporting.
    """
    source_root = tmp_path / f"{release_id}-source"
    write_release_outputs(
        source_root,
        release_id,
        smoke_test=smoke_test,
        omit=omit,
        job_records=job_records,
    )
    configfile = tmp_path / f"{release_id}.yaml"
    configfile.write_text(yaml.safe_dump({"smoke_test": smoke_test}))
    record_run_config(source_root, configfile)
    # Every dataset is reviewed as permitted, so releases publish.
    checkout = tmp_path / f"{release_id}-checkout"
    review_file = checkout / "conf/release/dataset_redistribution.yaml"
    review_file.parent.mkdir(parents=True)
    review = {
        "status": "permitted",
        "bundle_policy": "include",
        "license": "MIT",
        "source": "generated by afabench",
        "reviewed_by": "maintainer",
        "notes": None,
    }
    review_file.write_text(
        yaml.safe_dump({"datasets": dict.fromkeys(CATALOG.datasets, review)})
    )
    package_dir = tmp_path / f"{release_id}-package"
    saved = runner.invoke(
        app,
        [
            "save",
            str(package_dir),
            "--source-root",
            str(source_root),
            "--configfile",
            str(configfile),
            "--release-id",
            release_id,
            "--checkout",
            str(checkout),
        ],
    )
    assert saved.exit_code == 0, saved.output
    # Synthetic creation times order the catalog independently of how fast
    # the test saves its packages.
    manifest_path = package_dir / RELEASE_MANIFEST
    manifest = json.loads(manifest_path.read_text())
    manifest["created_at"] = created_at
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    if backdate:
        paths = sorted((package_dir / "output").rglob("*"))
        for offset, path in enumerate(paths):
            mtime = 1_700_000_000 + offset
            os.utime(path, (mtime, mtime))
    if smoke_test or local_only:
        transport.host_locally(package_dir)
        return package_dir
    published = invoke(transport, "publish", str(package_dir))
    assert published.exit_code == 0, published.output
    return package_dir


def download(
    transport: FakeReleaseTransport, destination_root: Path, *args: str
) -> Result:
    return invoke(
        transport,
        "download",
        *args,
        "--destination-root",
        str(destination_root),
    )


def restored_release_id(destination_root: Path) -> str:
    manifest_path = destination_root / RELEASE_MANIFEST
    return read_release_manifest(manifest_path).release_id


def restored_files(destination_root: Path) -> set[str]:
    """Return the restored outputs, leaving out the release's own files."""
    release_files = {RELEASE_MANIFEST, TABLE, BENCHMARK_CONFIG_FILENAME}
    return {
        path.relative_to(destination_root).as_posix()
        for path in destination_root.rglob("*")
        if path.is_file() and path.name not in release_files
    }


def restored_bundles(destination_root: Path) -> set[str]:
    return {
        path.split(".bundle/")[0] + ".bundle"
        for path in restored_files(destination_root)
        if ".bundle/" in path
    }


@pytest.mark.parametrize(
    "selection",
    [
        ["--all"],
        ["--output-category", "plots"],
        ["--payload-category", "job_duration_table"],
        [
            "--payload-category",
            "transformed_evaluation_table",
            "--output-category",
            "plots",
        ],
        ["--method", "beta", "--dataset", "cube"],
    ],
)
def test_download_reports_size_before_fetching_payloads(
    tmp_path: Path, selection: list[str]
) -> None:
    transport = FakeReleaseTransport()
    publish(tmp_path, transport, "sized", job_records=True)
    fetched: dict[str, bytes] = {}

    def before_download(path: str) -> None:
        if path.endswith("/release_manifest.json"):
            return
        print("Payload transfer started.")
        fetched.update(
            (name, content)
            for name, content in transport.files.items()
            if name == path or name.startswith(f"{path}/")
        )

    transport.before_download = before_download
    result = download(transport, tmp_path / "destination", "sized", *selection)

    assert result.exit_code == 0, result.output
    assert fetched
    total = sum(len(content) for content in fetched.values())
    assert (
        f"({total:,} bytes across {len(fetched):,} files; before cache reuse)."
        in result.output
    )
    assert result.output.index("Download size:") < result.output.index(
        "Payload transfer started."
    )


