def write_configfile(path: Path) -> Path:
    path.write_text(
        yaml.safe_dump({"methods": ["alpha"], "smoke_test": False})
    )
    return path


def save(tmp_path: Path, *extra: str) -> Result:
    """Save `tmp_path/source` as release `2026-10-cube`."""
    configfile = write_configfile(tmp_path / "run.yaml")
    if not (tmp_path / "source/workflow_config.json").exists():
        record_run_config(tmp_path / "source", configfile)
    checkout = tmp_path / "reviewed-checkout"
    review_file = checkout / "conf/release/dataset_redistribution.yaml"
    review_file.parent.mkdir(parents=True, exist_ok=True)
    review_file.write_text(
        yaml.safe_dump(
            {
                "datasets": {
                    dataset: {
                        "status": "permitted",
                        "bundle_policy": "include",
                        "license": "MIT",
                        "source": "generated by afabench",
                        "reviewed_by": "maintainer",
                        "notes": None,
                    }
                    for dataset in ["cube", "cube_without_noise"]
                }
            }
        )
    )
    return runner.invoke(
        app,
        [
            "save",
            str(tmp_path / "snapshot"),
            "--source-root",
            str(tmp_path / "source"),
            "--configfile",
            str(configfile),
            "--release-id",
            "2026-10-cube",
            "--checkout",
            str(checkout),
            *extra,
        ],
    )


def save_catalog(
    tmp_path: Path, catalog: Catalog | None = None, *extra: str
) -> Result:
    write_catalog(tmp_path / "source", catalog or Catalog(methods=[ALPHA]))
    result = save(tmp_path, *extra)
    assert result.exit_code == 0, result.output
    return result


def read_manifest(tmp_path: Path) -> dict[str, Any]:
    return json.loads(
        (tmp_path / "snapshot/release_manifest.json").read_text()
    )


def bundles(tmp_path: Path) -> dict[str, dict[str, Any]]:
    return {
        bundle["path"]: bundle for bundle in read_manifest(tmp_path)["bundles"]
    }


